// Builds web/nwc.js, the shell's NIP-47 wallet crypto (sign, NIP-44 v2, NIP-04),
// from the service's pinned nostr-tools and esbuild. Deterministic: tools/test.mjs
// rebuilds it and fails if the committed file differs.  node tools/build-nwc.mjs [--check]
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const req = createRequire(path.join(root, 'service', 'package.json'));
const esbuild = req('esbuild');
const ver = (p) => JSON.parse(fs.readFileSync(path.join(root, 'service/node_modules', p, 'package.json'), 'utf8')).version;
export async function buildNwc() {
  const r = await esbuild.build({
    entryPoints: [path.join(root, 'tools/nwc/entry.mjs')], bundle: true, minify: true, format: 'iife', target: 'es2020',
    legalComments: 'none', write: false, nodePaths: [path.join(root, 'service/node_modules')], logLevel: 'error',
  });
  const head = `/* nwc.js — generated by tools/build-nwc.mjs from nostr-tools ${ver('nostr-tools')} (MIT, includes @noble/* MIT), esbuild ${ver('esbuild')}. Do not edit. */\n`;
  return head + r.outputFiles[0].text;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const out = await buildNwc(), file = path.join(root, 'web/nwc.js');
  if (process.argv.includes('--check')) { if (fs.readFileSync(file, 'utf8') !== out) { console.error('web/nwc.js is stale: run node tools/build-nwc.mjs'); process.exit(1); } }
  else fs.writeFileSync(file, out);
}
